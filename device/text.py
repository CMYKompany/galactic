HEIGHT = 9      # rows including descenders
CAP = 7         # rows from the top of capitals to the baseline
SPACING = 1     # blank columns between characters

# Compiled: char -> tuple of column bitmasks (bit 0 = top row)
_GLYPHS = {}


def _compile():
    for ch in _SRC:
        rows = _SRC[ch].split("/")
        cols = []
        for x in range(len(rows[0])):
            m = 0
            for y in range(len(rows)):
                if rows[y][x] == "#":
                    m |= 1 << y
            cols.append(m)
        _GLYPHS[ch] = tuple(cols)


_compile()
_SRC = None     # free the source strings


def glyph(ch):
    g = _GLYPHS.get(ch)
    return g if g is not None else _GLYPHS["?"]


def measure(s):
    """Width of s in pixels."""
    if not s:
        return 0
    w = 0
    for ch in s:
        w += len(glyph(ch))
    return w + SPACING * (len(s) - 1)


def draw(gfx, s, x, y, color, clip_left=0, clip_right=53, clip_top=0, clip_bottom=11):
    """Draw s with its top-left at (x, y). Columns and rows outside the clip
    box are skipped, so scrolling text can be drawn partly off-screen."""
    fixed = not callable(color)
    if fixed:
        gfx.set_pen(gfx.create_pen(color[0], color[1], color[2]))
    for ch in s:
        g = glyph(ch)
        if x >= clip_right:
            break
        if x + len(g) > clip_left:
            for i in range(len(g)):
                cx = x + i
                m = g[i]
                if m == 0 or cx < clip_left or cx >= clip_right:
                    continue
                if not fixed:
                    c = color(cx)
                    gfx.set_pen(gfx.create_pen(c[0], c[1], c[2]))
                row = 0
                while m:
                    if m & 1:
                        cy = y + row
                        if clip_top <= cy < clip_bottom:
                            gfx.pixel(cx, cy)
                    m >>= 1
                    row += 1
        x += len(g) + SPACING
